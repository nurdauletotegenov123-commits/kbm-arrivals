def build(day):
    """→ BytesIO с .xlsx на день `day` (и соседние дни внутри)."""
    wb = Workbook()
    ws = wb.active
    ws.title = "План"
    ws.append([f"Ежедевная информация по поставке оборудование/материала на месторождение {day:%d.%m.%Y}"])
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(HEADER))
    ws.append(HEADER)
    sub = [None] * len(HEADER)
    sub[9], sub[10] = "Ф.И.О водителя", "Телефон"
    ws.append(sub)
    for c in range(1, len(HEADER) + 1):  # шапка в две строки
        if c not in (10, 11):
            ws.merge_cells(start_row=2, start_column=c, end_row=3, end_column=c)
    ws.merge_cells(start_row=2, start_column=10, end_row=2, end_column=11)
    ws.append([f"Планируемая поставка на {day:%d.%m.%Y}"])
    ws.merge_cells(start_row=ws.max_row, start_column=1, end_row=ws.max_row, end_column=len(HEADER))
    n = 0
    for truck in rows_for(day):
        first = ws.max_row + 1
        for item in truck:
            n += 1
            ws.append([n, *item])
        if len(truck) > 1:  # машина объединена на несколько строк груза
            for c in (7, 8, 9, 10, 11, 12):
                ws.merge_cells(start_row=first, start_column=c, end_row=ws.max_row, end_column=c)
    out = BytesIO()
    wb.save(out)
    out.seek(0)
    out.name = f"plan_{day:%d.%m.%Y}.xlsx"
    return out
